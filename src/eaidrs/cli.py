"""Command-line entry point: ``uv run eaidrs <command>``.

Commands
--------
manifest create   hash the configured raw files into data/MANIFEST.sha256
manifest verify   check the raw files against the committed manifest
audit             data-quality, class-by-day and class-by-split audit (one run folder)
prepare           clean + chronological split -> processed parquet (test split sealed)
"""

from __future__ import annotations

import argparse
import logging
import sys
from collections.abc import Sequence
from pathlib import Path

from eaidrs.core.config import DatasetConfig, load_dataset_config, load_split_config
from eaidrs.core.paths import data_dir, manifest_path, resolve_from_root
from eaidrs.data import audit, schema
from eaidrs.data.loading import load_clean_dataset, raw_dir_for
from eaidrs.data.manifest import build_manifest, verify_manifest, write_manifest
from eaidrs.data.splits import assign_splits, class_split_counts, split_summary
from eaidrs.data.store import processed_dir, write_splits
from eaidrs.tracking.run import tracked_run, write_json

logger = logging.getLogger("eaidrs")

DEFAULT_DATA_CONFIG = "configs/data/cicids2017.yaml"
DEFAULT_SPLIT_CONFIG = "configs/split/grouped_by_day_label.yaml"


class CommandError(RuntimeError):
    """A command could not run; the message is shown to the user."""


def _raw_files(config: DatasetConfig) -> list[Path]:
    directory = raw_dir_for(config)
    return [directory / f.name for f in config.files]


def _check_manifest(config: DatasetConfig, *, required: bool) -> None:
    """Verify raw files against the manifest. Missing manifest is an error only if required."""
    manifest = manifest_path()
    if not manifest.is_file():
        if required:
            raise CommandError(
                f"{manifest} not found. Run `eaidrs manifest create` and commit it first."
            )
        logger.warning("no data manifest at %s: dataset integrity NOT verified", manifest)
        return
    problems = verify_manifest(manifest, data_dir())
    if problems:
        raise CommandError("data manifest check failed:\n  " + "\n  ".join(problems))
    logger.info("data manifest verified (%s)", manifest)


def cmd_manifest(args: argparse.Namespace) -> None:
    config = load_dataset_config(args.data_config)
    manifest = manifest_path()
    if args.action == "create":
        if manifest.exists() and not args.force:
            raise CommandError(f"{manifest} exists; pass --force to overwrite it")
        entries = build_manifest(data_dir(), _raw_files(config))
        write_manifest(entries, manifest)
        print(f"wrote {len(entries)} entries to {manifest}")
        return
    problems = verify_manifest(manifest, data_dir()) if manifest.is_file() else ["no manifest"]
    if problems:
        raise CommandError("manifest verification failed:\n  " + "\n  ".join(problems))
    print(f"OK: all files in {manifest} match")


def cmd_audit(args: argparse.Namespace) -> None:
    data_config_path = resolve_from_root(args.data_config)
    split_paths = [resolve_from_root(p) for p in (args.split_config or [DEFAULT_SPLIT_CONFIG])]
    config = load_dataset_config(data_config_path)
    split_configs = [load_split_config(p) for p in split_paths]
    _check_manifest(config, required=False)

    configs = {"data": data_config_path}
    configs.update({f"split_{c.name}": p for c, p in zip(split_configs, split_paths, strict=True)})
    with tracked_run("audit", configs=configs) as run:
        dataset = load_clean_dataset(config)
        frame, features = dataset.frame, dataset.feature_columns
        sizes = {p.name: p.stat().st_size for p in _raw_files(config)}

        inventory = audit.file_inventory(dataset, sizes)
        quality = audit.quality_table(dataset.reports, features)
        by_day = audit.class_by_day(frame, config.day_order)
        episodes = audit.class_time_ranges(frame)
        constant = audit.constant_columns(frame, features)
        duplicates = audit.duplicate_row_count(frame, [*features, schema.LABEL])

        run.save_json("cleaning_reports.json", [r.to_dict() for r in dataset.reports])
        run.save_table("file_inventory.csv", inventory, index=False)
        run.save_table("quality.csv", quality)
        run.save_table("class_by_day.csv", by_day)
        run.save_table("class_time_ranges.csv", episodes, index=False)

        report = [
            f"# Dataset audit: {config.name} ({config.version})",
            "",
            f"Run: `{run.run_id}`. Generated by `eaidrs audit`; do not edit by hand.",
            "",
            f"Rows after cleaning: {len(frame)} · features: {len(features)} · "
            f"exact duplicate rows (features + label): {duplicates}",
            "",
            "## File inventory",
            audit.markdown_table(inventory, index=False),
            "",
            "## Data quality (columns with any issue)",
            audit.markdown_table(quality) if not quality.empty else "No issues found.",
            "",
            f"Constant columns over the whole dataset (informational): {constant or 'none'}",
            "",
            "## Class by day",
            audit.markdown_table(by_day),
            "",
            "## Class time ranges (episodes)",
            audit.markdown_table(episodes, index=False),
        ]

        split_metrics: dict[str, dict[str, object]] = {}
        for split_config in split_configs:
            split = assign_splits(frame, split_config)
            summary = split_summary(frame, split, split_config)
            summary["cross_split_duplicates"] = audit.cross_split_duplicates(
                frame, split, [*features, schema.LABEL]
            )
            run.save_json(f"split_summary_{split_config.name}.json", summary)
            counts = class_split_counts(frame, split)
            run.save_table(f"class_by_split_{split_config.name}.csv", counts)
            report += [
                "",
                f"## Split `{split_config.name}` ({split_config.strategy})",
                audit.markdown_table(counts),
                "",
                f"Evaluable classes (≥ {split_config.min_class_support} flows in every split): "
                f"{summary['evaluable_classes']}",
                "",
                f"Classes absent from train: {summary['classes_absent_from_train']}",
                "",
                f"Val/test rows identical to a training row: {summary['cross_split_duplicates']}",
                "",
                f"Invariant violations: {summary['invariant_violations'] or 'none'}",
            ]
            split_metrics[split_config.name] = {
                "evaluable_classes": summary["evaluable_classes"],
                "classes_absent_from_train": summary["classes_absent_from_train"],
                "invariant_violations": len(summary["invariant_violations"]),
            }
        run.save_text("audit_report.md", "\n".join(report) + "\n")
        run.metrics = {
            "rows": len(frame),
            "features": len(features),
            "duplicate_rows": duplicates,
            "constant_columns": constant,
            "splits": split_metrics,
        }
    print(f"audit written to {run.path}")


def cmd_prepare(args: argparse.Namespace) -> None:
    data_config_path = resolve_from_root(args.data_config)
    split_config_path = resolve_from_root(args.split_config)
    config = load_dataset_config(data_config_path)
    split_config = load_split_config(split_config_path)
    _check_manifest(config, required=not args.allow_unverified_data)

    configs = {"data": data_config_path, "split": split_config_path}
    with tracked_run(f"prepare_{split_config.name}", configs=configs) as run:
        dataset = load_clean_dataset(config)
        split = assign_splits(dataset.frame, split_config)
        summary = split_summary(dataset.frame, split, split_config)
        if summary["invariant_violations"]:
            raise CommandError(
                "chronological split invariants violated:\n  "
                + "\n  ".join(summary["invariant_violations"])
            )
        out_dir = processed_dir(config.name, split_config.name)
        written = write_splits(dataset.frame, split, out_dir)
        summary["files"] = {k: v.as_posix() for k, v in written.items()}
        summary["source_run"] = run.run_id
        run.save_json("split_summary.json", summary)
        write_json(out_dir / "split_summary.json", summary)
        run.metrics = {
            "rows": {k: v["rows"] for k, v in summary["splits"].items()},
            "evaluable_classes": summary["evaluable_classes"],
        }
    print(f"processed splits written to {out_dir} (run {run.run_id})")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="eaidrs", description=__doc__.split("\n\n")[0])
    parser.add_argument("-v", "--verbose", action="store_true", help="debug logging")
    commands = parser.add_subparsers(dest="command", required=True)

    manifest = commands.add_parser("manifest", help="create or verify the raw-data manifest")
    manifest.add_argument("action", choices=["create", "verify"])
    manifest.add_argument("--data-config", default=DEFAULT_DATA_CONFIG)
    manifest.add_argument("--force", action="store_true", help="overwrite an existing manifest")
    manifest.set_defaults(handler=cmd_manifest)

    audit_parser = commands.add_parser("audit", help="audit the dataset and candidate splits")
    audit_parser.add_argument("--data-config", default=DEFAULT_DATA_CONFIG)
    audit_parser.add_argument(
        "--split-config",
        action="append",
        help=f"repeatable; default {DEFAULT_SPLIT_CONFIG}",
    )
    audit_parser.set_defaults(handler=cmd_audit)

    prepare = commands.add_parser("prepare", help="write processed chronological splits")
    prepare.add_argument("--data-config", default=DEFAULT_DATA_CONFIG)
    prepare.add_argument("--split-config", default=DEFAULT_SPLIT_CONFIG)
    prepare.add_argument(
        "--allow-unverified-data",
        action="store_true",
        help="run without a data manifest (smoke tests only; never for reported results)",
    )
    prepare.set_defaults(handler=cmd_prepare)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    try:
        args.handler(args)
    except (CommandError, FileNotFoundError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
